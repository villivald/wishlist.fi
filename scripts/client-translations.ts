import { readFileSync, writeFileSync } from "node:fs";
import { format } from "prettier";
import english from "../src/i18n/messages/en.json";
import { localizationReferences } from "./localization-source";

const filename = "src/i18n/client-keys.ts";
const { clientKeys, clientCatalogLeaks } = localizationReferences(
  Object.keys(english),
);
if (clientCatalogLeaks.length)
  throw new Error(
    `Full translation catalogs reached client/shared code: ${clientCatalogLeaks.join(", ")}`,
  );
const output = await format(
  `// Generated by npm run localization:generate. Do not edit by hand.\nimport type { TextKey } from "./translator";\nexport const clientTextKeys = ${JSON.stringify(clientKeys)} as const satisfies readonly TextKey[];\n`,
  { parser: "typescript" },
);
if (process.argv.includes("--write")) {
  writeFileSync(filename, output);
} else if (readFileSync(filename, "utf8") !== output) {
  throw new Error(
    "Client translation references changed. Run npm run localization:generate.",
  );
}
console.log(`Client translations: ${clientKeys.length} referenced keys.`);
